#!/usr/bin/env node
/**
 * Generates TypeScript model interfaces, SCHEMA field registry, and URI constants from pyDEXPI metadata.
 * Offline dev-only script. The generated output is committed to source control.
 */

import * as fs from 'fs';
import * as path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..');

// 1. Run python extraction script
console.log('Extracting pyDEXPI schema via Python...');
const venvPython = path.join(REPO_ROOT, '.venv', 'bin', 'python');
const pyScript = path.join(REPO_ROOT, 'scripts', 'extract_schema.py');
execSync(`"${venvPython}" "${pyScript}"`, { stdio: 'inherit' });

const schemaJsonPath = path.join(REPO_ROOT, 'scripts', 'pydexpi-schema.json');
const schema = JSON.parse(fs.readFileSync(schemaJsonPath, 'utf-8'));

const MODEL_DIR = path.join(REPO_ROOT, 'src', 'model');
const CLASSES_DIR = path.join(MODEL_DIR, 'classes');
fs.mkdirSync(CLASSES_DIR, { recursive: true });

// 2. Generate uris.ts
console.log('Generating src/model/uris.ts...');
const urisContent = `/**
 * [GENERATED BY scripts/gen-model.mjs - DO NOT EDIT MANUALLY]
 * pyDEXPI 1.2.0 URI constants and bidirectional lookups.
 */

export const CLASS_URIS: Record<string, string> = ${JSON.stringify(schema.uris, null, 2)};

export const URI_TO_CLASS: Record<string, string> = Object.fromEntries(
  Object.entries(CLASS_URIS).map(([cls, uri]) => [uri, cls])
);

export function uriForClass(className: string): string {
  return CLASS_URIS[className] || \`http://sandbox.dexpi.org/rdl/\${className}\`;
}

export function classForUri(uri: string): string | undefined {
  return URI_TO_CLASS[uri];
}
`;
fs.writeFileSync(path.join(MODEL_DIR, 'uris.ts'), urisContent, 'utf-8');

// 3. Generate enumerations.ts
console.log('Generating src/model/classes/enumerations.ts...');
let enumsContent = `/**
 * [GENERATED BY scripts/gen-model.mjs - DO NOT EDIT MANUALLY]
 * pyDEXPI 1.2.0 Enumeration types.
 */\n\n`;

for (const [enumName, values] of Object.entries(schema.enums)) {
  const union = values.map((v) => `'${v}'`).join(' | ');
  enumsContent += `export type ${enumName} = ${union || 'string'};\n`;
}
fs.writeFileSync(path.join(CLASSES_DIR, 'enumerations.ts'), enumsContent, 'utf-8');

