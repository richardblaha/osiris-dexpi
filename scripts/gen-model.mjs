// 16. Generate registry.ts
console.log('Generating src/model/registry.ts...');
const simplifiedSchema = {};
for (const [clsName, clsInfo] of Object.entries(schema.classes)) {
  const fields = {};
  for (const [fName, fMeta] of Object.entries(clsInfo.fields)) {
    fields[fName] = {
      category: fMeta.category || undefined,
      isList: fMeta.isList,
      required: fMeta.required,
      type: fMeta.type,
    };
  }
  simplifiedSchema[clsName] = fields;
}

const registryContent = `/**
 * [GENERATED BY scripts/gen-model.mjs - DO NOT EDIT MANUALLY]
 * pyDEXPI 1.2.0 Field Registry (SCHEMA) across all classes.
 */

export interface FieldMeta {
  category?: 'composition' | 'reference' | 'data';
  isList: boolean;
  required: boolean;
  type?: string;
}

export const SCHEMA: Record<string, Record<string, FieldMeta>> = ${JSON.stringify(simplifiedSchema, null, 2)};

export function getFieldMeta(className: string, fieldName: string): FieldMeta | undefined {
  const clsFields = SCHEMA[className];
  if (clsFields && clsFields[fieldName]) {
    return clsFields[fieldName];
  }
  return undefined;
}
`;
fs.writeFileSync(path.join(MODEL_DIR, 'registry.ts'), registryContent, 'utf-8');

